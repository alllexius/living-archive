/* Read one value safely: wrong type → original; out of range → nearest end. */
function clean(f, v) {
  if (f.type === 'bool') return typeof v === 'boolean' ? v : f.def;
  if (f.type === 'choice') return f.options.includes(v) ? v : f.def;
  v = Number(v);
  if (!isFinite(v)) return f.def;
  return Math.min(f.max, Math.max(f.min, v));
}
function readSettings(src) {
  const out = {}, notes = [];
  for (const f of fields) {
    const has = !!src && Object.prototype.hasOwnProperty.call(src, f.key);
    out[f.key] = has ? clean(f, src[f.key]) : f.def;
    if (has && out[f.key] !== src[f.key]) notes.push(`${f.key}: ${JSON.stringify(src[f.key])} \u2192 ${out[f.key]}`);
    if (src && !has) notes.push(`${f.key}: missing \u2192 ${f.def}`);
  }
  return { values: out, notes };
}

